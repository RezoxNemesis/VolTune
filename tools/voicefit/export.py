"""Write VolTune's src/engine/learned_data.ts from fitted voices and emotions.

python export.py voices.json emotions.json ../../src/engine/learned_data.ts
voices.json: [{id, name, gender, tone, timbre, fit: "fit_x.json" | delivery + delta, phrasing, learnedFrom, sing?}]
"""
import base64, json, os, sys, numpy as np

def b64(vec):
    a = np.asarray(vec, dtype=np.float16)
    assert a.shape == (128,), a.shape
    return base64.b64encode(a.astype('<f2').tobytes()).decode()

def mix_str(m):
    return '+'.join(f'{v}*{round(w, 3)}' for v, w in m) if len(m) > 1 else m[0][0]

def main(voices_path, emotions_path, out_path):
    base = os.path.dirname(os.path.abspath(voices_path))
    voices = json.load(open(voices_path))
    emo = json.load(open(emotions_path))
    rows = []
    for v in voices:
        if 'fit' in v:
            f = json.load(open(os.path.join(base, v['fit'])))
            delivery, delta = f['mix'], f['delta']
        else:
            delivery, delta = v['delivery'], v['delta']
        if v.get('delta_add'):
            delta = (np.asarray(delta) + np.asarray(v['delta_add'])).tolist()
        timbre = v['timbre'] if isinstance(v['timbre'], str) else mix_str(v['timbre'])
        rows.append({
            'id': v['id'], 'name': v['name'], 'gender': v['gender'], 'tone': v['tone'],
            'timbre': timbre, 'delivery': delivery if isinstance(delivery, str) else mix_str(delivery),
            'offset': b64(delta), 'phrasing': v['phrasing'], 'learnedFrom': v['learnedFrom'],
            **({'sing': v['sing']} if v.get('sing') else {}),
        })
    moods = ['happy', 'excited', 'sad', 'crying', 'angry', 'scared', 'loving', 'surprised', 'serious', 'tired', 'pleading']
    lines = ['/**', ' * Generated by tools/voicefit/export.py — do not edit by hand. Re-run the fit to change a voice.',
             ' * Offsets are 128 float16 numbers in base64 (see learned.ts).', ' */',
             'import type { LearnedVoice, Mood } from "./learned";', '',
             'export const LEARNED_DATA: LearnedVoice[] = [']
    for r in rows:
        lines.append('  ' + json.dumps(r, ensure_ascii=False) + ',')
    lines += ['];', '', '/** Learned delivery-half direction of each mood, shared by every voice. */',
              'export const EMOTION_DATA: Record<Mood, string> = {']
    for m in moods:
        lines.append(f'  {m}: "{b64(emo[m]["delta"])}",')
    lines += ['};', '']
    open(out_path, 'w').write('\n'.join(lines))
    print(f'wrote {out_path}: {len(rows)} voices, {len(moods)} moods')

if __name__ == '__main__':
    main(*sys.argv[1:4])
